def tr(key: str, lang: str = "en", **kw) -> str:
    pair = _S.get(key)
    if pair is None:
        return key
    s = pair[1] if lang == "es" else pair[0]
    return s.format(**kw) if kw else s


def issue_text(issue, lang: str = "en") -> str:
    mark = "✖" if issue.level == "error" else "⚠"
    return f"{mark} " + tr("i_" + issue.code, lang, **issue.args)
